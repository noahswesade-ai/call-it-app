// Turns content/question-bank.txt (the same text as the "Question Bank" tab of the
// Underdog Google Doc) into src/content/bank.generated.ts.
// Usage: node tools/build-questions.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = process.argv[2] ? path.resolve(process.argv[2]) : path.join(root, 'content', 'question-bank.txt');
const OUT = path.join(root, 'src', 'content', 'bank.generated.ts');

const CATS = {
  geography: 'geography', history: 'history', 'basic knowledge': 'basic', 'pop culture': 'popculture',
  sports: 'sports', physical: 'physical', 'know your friends': 'kyf', party: 'party', spicy: 'spicy',
};
const TYPES = { answer: 'SPOKEN_EXACT', number: 'SPOKEN_CLOSEST', turns: 'TURN_BASED', challenge: 'HOST_JUDGED' };
const DIFF = { easy: 'E', medium: 'M', hard: 'H' };

export function parseBank(text) {
  const out = [];
  const problems = [];
  const counters = {};
  const seen = new Set();
  let cat;
  text.split(/\r?\n/).forEach((raw, i) => {
    // Accept the plain text file AND the Google Doc read back as Markdown
    // (headings as "# Geography", escaped brackets like "\[Answer · Easy\]", bullets).
    const line = raw.trim().replace(/\\([\[\]()*_#>=+\-.!|`{}~])/g, '$1').replace(/^[-•*]\s+/, '').replace(/\*\*/g, '');
    if (!line) return;
    if (line.startsWith('#')) {
      const name = line.replace(/^#+/, '').trim().toLowerCase();
      if (CATS[name]) cat = CATS[name];
      return; // other # lines are notes
    }
    if (!cat || !line.startsWith('[')) return; // notes and instructions
    const m = line.match(/^\[([^\]]+)\]\s*(.+)$/);
    if (!m) return problems.push(`line ${i + 1}: no [Type] tag: ${line.slice(0, 60)}`);
    const tag = m[1].split(/[·|,/-]/).map((t) => t.trim().toLowerCase()).filter(Boolean);
    let rest = m[2];
    let answer, numeric;
    const arrow = rest.indexOf('=>');
    if (arrow >= 0) {
      answer = rest.slice(arrow + 2).trim();
      rest = rest.slice(0, arrow).trim();
      const nm = answer.match(/\s=\s*(-?[\d.,_]+)\s*$/);
      if (nm) {
        numeric = Number(nm[1].replace(/[,_]/g, ''));
        answer = answer.slice(0, nm.index).trim();
      }
    }
    const prompt = rest.replace(/\{friend\}/gi, '{S}').trim();
    const key = prompt.toLowerCase();
    if (seen.has(key)) problems.push(`line ${i + 1}: duplicate question: ${prompt.slice(0, 60)}`);
    seen.add(key);
    counters[cat] = (counters[cat] ?? 0) + 1;
    const id = `${cat}-${String(counters[cat]).padStart(3, '0')}`;
    const q = { id, category: cat, prompt };
    if (tag[0] === 'friend' || tag[0] === 'friend number') {
      Object.assign(q, { type: 'SUBJECT_JUDGED', difficulty: 'M', closest: tag[0] === 'friend number' || tag.includes('number') });
    } else if (tag[0] === 'room game') {
      Object.assign(q, { type: 'HOST_JUDGED', difficulty: 'M', repeatable: true });
    } else {
      const type = TYPES[tag[0]];
      if (!type) return problems.push(`line ${i + 1}: unknown type "${tag[0]}"`);
      q.type = type;
      q.difficulty = DIFF[tag[1]] ?? 'M';
      if (answer) q.answer = answer;
      if (type === 'SPOKEN_CLOSEST') {
        if (numeric === undefined) problems.push(`line ${i + 1}: Number question without "= number": ${prompt.slice(0, 50)}`);
        else q.numericAnswer = numeric;
      }
      if (type === 'SPOKEN_EXACT' && !answer) problems.push(`line ${i + 1}: Answer question without "=> answer": ${prompt.slice(0, 50)}`);
    }
    out.push(q);
  });
  return { questions: out, problems, counters };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { questions, problems, counters } = parseBank(fs.readFileSync(SRC, 'utf8'));
  const body = `// GENERATED by tools/build-questions.mjs from content/question-bank.txt. Do not edit by hand.\nimport type { Question } from '@/game/types';\n\nexport const BANK: Question[] = ${JSON.stringify(questions, null, 1)};\n`;
  fs.writeFileSync(OUT, body);
  console.log('Questions per category:', counters, '· total', questions.length);
  if (problems.length) {
    console.log(`\n${problems.length} problem(s):\n` + problems.join('\n'));
    process.exitCode = 1;
  }
}
