import React from 'react';
import { Image, View } from 'react-native';
import type { AvatarLoadout } from '@/game/types';
import { SLOTS, type AccessorySlot } from './catalog';
import FIT from './fit.json';
import { ACCESSORY_IMAGES, AVATAR_IMAGES, WORN_IMAGES } from './images';

/**
 * Draws a player's animal with the right expression plus any accessories.
 *
 * Moods (each animal has three hand-drawn faces):
 *   neutral – lobby, choosing screens, waiting
 *   happy   – winning, correct calls, podium
 *   sad     – losing, drinking, being the Underdog
 * "drink" and "nervous" are kept as aliases of sad so older call sites still work.
 *
 * Accessory placement comes from `fit.json`, generated by tools/fit_accessories2.py (hand-measured head landmarks),
 * which measures each animal's eyes, head and chin so every item is fitted to every
 * animal individually. Each entry is one or more rectangles
 * [left, top, width, height, behindFace, crop?] in fractions of the avatar size;
 * crop = [y0, y1, x0, x1] shows only part of the art (earrings); a 7th entry names a
 * variant of the art drawn instead (e.g. 'cups': just the headphone cups, in front).
 */
export type Mood = 'neutral' | 'happy' | 'sad' | 'drink' | 'nervous';

type Rect = [number, number, number, number, boolean, (number[] | null)?, string?];
const FITS = FIT as unknown as Record<string, Record<string, Rect[]>>;

interface Props {
  avatar: AvatarLoadout;
  size?: number;
  mood?: Mood;
  /** Hide accessories (e.g. shop thumbnails). */
  bare?: boolean;
}

// Front-of-face drawing order (later = on top).
const FRONT_ORDER: AccessorySlot[] = ['neck', 'mouth', 'eyes', 'ears', 'head'];

function moodKey(mood: Mood): 'neutral' | 'happy' | 'sad' {
  if (mood === 'happy') return 'happy';
  if (mood === 'sad' || mood === 'drink' || mood === 'nervous') return 'sad';
  return 'neutral';
}

export function AnimalAvatar({ avatar, size = 64, mood = 'neutral', bare }: Props) {
  const m = moodKey(mood);
  const src = AVATAR_IMAGES[`${avatar.animal}-${m}`] ?? AVATAR_IMAGES[`dog-${m}`];
  const fits = FITS[avatar.animal] ?? FITS.dog;

  const layers: { key: string; id: string; rect: Rect }[] = [];
  if (!bare) {
    for (const slot of SLOTS) {
      const id = avatar[slot];
      if (!id || !fits[id] || !ACCESSORY_IMAGES[id]) continue;
      fits[id].forEach((rect, i) => layers.push({ key: `${slot}-${i}`, id, rect }));
    }
  }
  const slotOf = (key: string) => key.split('-')[0] as AccessorySlot;
  const behind = layers.filter((l) => l.rect[4]);
  const front = layers.filter((l) => !l.rect[4]).sort((a, b) => FRONT_ORDER.indexOf(slotOf(a.key)) - FRONT_ORDER.indexOf(slotOf(b.key)));

  return (
    <View style={{ width: size, height: size }}>
      {behind.map((l) => (
        <Layer key={l.key} id={l.id} rect={l.rect} size={size} />
      ))}
      <Image source={src} style={{ width: size, height: size }} resizeMode="contain" />
      {front.map((l) => (
        <Layer key={l.key} id={l.id} rect={l.rect} size={size} />
      ))}
    </View>
  );
}

function Layer({ id, rect, size }: { id: string; rect: Rect; size: number }) {
  const [l, t, w, h, , crop, variant] = rect;
  const left = l * size;
  const top = t * size;
  const width = w * size;
  const height = h * size;
  const img = (variant && WORN_IMAGES[`${id}-${variant}`]) || WORN_IMAGES[id] || ACCESSORY_IMAGES[id];
  if (!crop) {
    return <Image source={img} resizeMode="stretch" style={{ position: 'absolute', left, top, width, height }} />;
  }
  const [y0, y1, x0, x1] = crop;
  return (
    <View
      style={{
        position: 'absolute',
        left: left + x0 * width,
        top: top + y0 * height,
        width: (x1 - x0) * width,
        height: (y1 - y0) * height,
        overflow: 'hidden',
      }}
    >
      <Image source={img} resizeMode="stretch" style={{ width, height, marginLeft: -x0 * width, marginTop: -y0 * height }} />
    </View>
  );
}
